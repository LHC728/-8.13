def _fresh_batch_state(rep: int):
    """Build the t=0 ObservableState / PosteriorState / ContinuationWorld
    for a fresh 100-device batch under h2_tuning."""
    log = [
        {"event_type": "TRUE_STATE_GENERATED", "event_time": "0",
         "device_id": 1, "true_state": {"A": False, "B": False, "C": False}},
        {"event_type": "TRUE_STATE_GENERATED", "event_time": "0",
         "device_id": 2, "true_state": {"A": False, "B": False, "C": False}},
        {"event_type": "SHIFT_CHANGE", "event_time": "0", "shift_index": 0,
         "shift_start": "0", "shift_end": "300", "on_duty_squad": 0,
         "squad_id": 0},
    ]
    st = obs.project_log_prefix(log, Fraction(0), batch_size=BATCH_SIZE)
    post = ps.PosteriorState.from_observable(st)
    prov = pk.physical_post_provider(NS, MASTER_SEED, rep, BATCH_SIZE,
                                     ("A", "B", "C", "E"))
    # hidden truth for the two preloaded devices from the physical prior
    ux = {1: prov.u_x(1), 2: prov.u_x(2)}
    ud = {1: prov.u_d(1), 2: prov.u_d(2)}
    ul = {r: prov.u_l(r, 1) for r in ("A", "B", "C", "E")}
    world = cont.rebuild_continuation_world(st, post, ux, ud, ul)
    return st, post, world, prov


def generate_tuning_batch(rep: int, cfg: re1.RolloutConfig
                          ) -> dict[str, Any]:
    """Run one h2_tuning physical batch under the H1 baseline (no H2
    policy)."""
    st, post, world, prov = _fresh_batch_state(rep)
    eng = br.H2BatchRunner(st, post, world, prov, cfg, None, MASTER_SEED, rep,
                           policy_enabled=False)
    t0 = time.perf_counter()
    out = eng.run()
    wall = time.perf_counter() - t0
    return {"rep": rep, "t_end": out.t_end, "events": list(out.events),
            "wallclock_s": wall,
            "passed": out.devices_passed, "exited": out.devices_exited}


def collect_eligible_points(batch_log: list[dict], K: Fraction,
                            batch_size: int
                            ) -> list[dict[str, Any]]:
    """All H2-eligible decision points of a batch, in time order."""
    pts = dpimpl.reconstruct_decision_points(batch_log, K,
                                             batch_size=batch_size,
                                             t_end=Fraction(10 ** 9))
    out = []
    for p in pts:
        wait_legal = dpimpl.A_WAIT_EVENT in p.legal_actions
        pm_legal = (dpimpl.A_PM_WITH_HEAD in p.legal_actions
                    or dpimpl.A_PM_IDLE in p.legal_actions)
        if not (wait_legal or pm_legal):
            continue
        out.append({
            "time": p.time, "resource": p.resource, "kind": p.kind,
            "legal_actions": list(p.legal_actions),
            "wait_legal": wait_legal, "pm_legal": pm_legal,
            "is_both": wait_legal and pm_legal,
            "wait_anchor_time": (p.wait_anchor.completion_time
                                 if p.wait_anchor is not None else None),
            "quota_class": ("WAIT" if wait_legal else "PM"),
        })
    out.sort(key=lambda x: (x["time"], x["resource"]))
    return out


def build_b1_sample(batches: list[list[dict]], K: Fraction, batch_size: int
                    ) -> dict[str, Any]:
    """Deterministic B-1 sample: batch order then intra-batch time order,
    first 50 wait-eligible + first 50 PM-only; cap 120."""
    wait_pts: list[dict] = []
    pm_pts: list[dict] = []
    for bi, blog in enumerate(batches):
        for p in collect_eligible_points(blog, K, batch_size):
            p["batch"] = bi
            if p["quota_class"] == "WAIT":
                if len(wait_pts) < WAIT_CAP:
                    wait_pts.append(p)
            else:
                if len(pm_pts) < PM_CAP:
                    pm_pts.append(p)
    sample = wait_pts + pm_pts
    if len(sample) > SAMPLE_CAP:
        sample = sample[:SAMPLE_CAP]
    # deterministic per-point dp index (0-based across the diagnostic
    # sample; SPEC 6.2 dp = 0-based decision-point index -- for the offline
    # diagnostics the index is the sample position so CRN keys are stable
    # across salt / M evaluations of the same point).
    for idx, p in enumerate(sample):
        p["dp"] = idx
    n_wait = len(wait_pts)
    n_pm = len(pm_pts)
    n_both = sum(1 for p in sample if p["is_both"])
    return {"n": len(sample), "n_wait": n_wait, "n_pm": n_pm,
            "n_both": n_both, "wait_cap": WAIT_CAP, "pm_cap": PM_CAP,
            "sample_cap": SAMPLE_CAP, "points": sample}


