def _c23_policy_check(sample: dict, batch_logs: list[list[dict]]
                      ) -> dict[str, Any]:
    """C23 policy determinism: hidden-world variants do not change the
    policy action at a sample point."""
    failures = []
    if not sample["points"]:
        return {"check": "C23_POLICY", "status": "FAIL",
                "failures": ["empty sample"]}
    p = sample["points"][0]
    blog = batch_logs[p["batch"]]
    # variant logs with different hidden annotations
    variants = []
    for i, mut in enumerate((lambda r: r.update(true_state={"A": True, "B": True, "C": True}),
                             lambda r: r.update(lifetime_h="999"),
                             lambda r: r.update(u="0.999"))):
        vlog = []
        for r in blog:
            rec = dict(r)
            mut(rec)
            vlog.append(rec)
        variants.append(vlog)
    chosen = []
    for vlog in [blog] + variants:
        ctx = _point_context(p, vlog, BATCH_SIZE)
        dec = pol.evaluate_decision_point(
            ctx["state"], ctx["posterior"], ctx["world"], ctx["provider"],
            ctx["cfg"], p["dp"], p["resource"], p["kind"],
            p["quota_class"], tuple(p["legal_actions"]), ctx["log_prefix"],
            MASTER_SEED, p["batch"], wait_anchor_time=p.get("wait_anchor_time"),
            M=4)  # small M for the C23 determinism check
        chosen.append(dec.chosen)
    if len(set(chosen)) != 1:
        failures.append(f"hidden variants changed the action: {chosen}")
    return {"check": "C23_POLICY", "status": "PASS" if not failures else "FAIL",
            "failures": failures, "actions_by_variant": chosen}


