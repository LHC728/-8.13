def _point_context(p: dict, batch_log: list[dict], batch_size: int):
    """Build (state, posterior, world, cfg, log_prefix) for one sample
    point, evaluating from the observable prefix AT the point's time."""
    t = p["time"]
    prefix = [r for r in batch_log
              if Fraction(r["event_time"]) <= t]
    st = obs.project_log_prefix(prefix, t, batch_size=batch_size)
    post = ps.PosteriorState.from_observable(st)
    prov = pk.physical_post_provider(NS, MASTER_SEED, p["batch"], batch_size,
                                     ("A", "B", "C", "E"))
    ux = {d.device_id: prov.u_x(d.device_id) for d in st.devices}
    ud = {d.device_id: prov.u_d(d.device_id) for d in st.devices}
    ul = {r: prov.u_l(r, 1) for r in ("A", "B", "C", "E")}
    world = cont.rebuild_continuation_world(st, post, ux, ud, ul)
    cfg = re1.RolloutConfig(batch_size=batch_size,
                            shift_length_h=K, shifts_per_day=2,
                            scenario="q3_two_shift",
                            tau_pm=re1.NO_PM_BEFORE_MANDATORY)
    return {"state": st, "posterior": post, "world": world,
            "provider": prov, "cfg": cfg, "log_prefix": prefix}


def _cp95_binomial(x: int, n: int) -> tuple[float, float]:
    """Exact Clopper-Pearson 95% two-sided interval (disclosure only)."""
    if n == 0:
        return (0.0, 1.0)
    if x == 0:
        return (0.0, 1 - (0.025) ** (1 / n))
    if x == n:
        return ((0.025) ** (1 / n), 1.0)
    lo = _cp_lower(x, n)
    hi = _cp_upper(x, n)
    return (lo, hi)


def _cp_lower(x: int, n: int) -> float:
    """Clopper-Pearson lower bound: p_lo solves P(X <= x-1 | p_lo) = 0.975
    (pbinom is decreasing in p, so pbinom >= 0.975 means p < p_lo)."""
    lo = 0.0
    hi = float(x) / n
    for _ in range(60):
        mid = (lo + hi) / 2
        if _pbinom(x - 1, n, mid) >= 0.975:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def _cp_upper(x: int, n: int) -> float:
    """Clopper-Pearson upper bound: p_hi solves P(X <= x | p_hi) = 0.025
    (pbinom <= 0.025 means p > p_hi)."""
    lo = float(x) / n
    hi = 1.0
    for _ in range(60):
        mid = (lo + hi) / 2
        if _pbinom(x, n, mid) <= 0.025:
            hi = mid
        else:
            lo = mid
    return (lo + hi) / 2


def _pbinom(x: int, n: int, p: float) -> float:
    import math
    if p <= 0:
        return 1.0 if x >= n else 0.0
    if p >= 1:
        return 0.0
    total = 0.0
    for k in range(0, x + 1):
        total += math.comb(n, k) * (p ** k) * ((1 - p) ** (n - k))
    return total


def evaluate_sample(sample: dict, batches: list[list[dict]],
                    salt: str, M: int, batch_size: int
                    ) -> dict[str, Any]:
    """Evaluate the B-1 sample with a given salt / M; return chosen actions
    + deviation info."""
    rows = []
    chosen = []
    n_dev = 0
    dev_types: dict[str, int] = {}
    for p in sample["points"]:
        ctx = _point_context(p, batches[p["batch"]], batch_size)
        dec = pol.evaluate_decision_point(
            ctx["state"], ctx["posterior"], ctx["world"], ctx["provider"],
            ctx["cfg"], p["dp"], p["resource"], p["kind"],
            p["quota_class"], tuple(p["legal_actions"]), ctx["log_prefix"],
            MASTER_SEED, p["batch"], wait_anchor_time=p.get("wait_anchor_time"),
            M=M, salt=salt)
        chosen.append(dec.chosen)
        if dec.deviated:
            n_dev += 1
            dev_types[dec.chosen] = dev_types.get(dec.chosen, 0) + 1
        rows.append({"point": p, "chosen": dec.chosen,
                     "deviated": dec.deviated,
                     "estimates": {a: e.to_canonical_dict()
                                   for a, e in sorted(dec.estimates.items())}})
    n = len(chosen)
    return {"n": n, "chosen": chosen, "rows": rows,
            "n_deviated": n_dev,
            "deviation_rate": (n_dev / n) if n else 0.0,
            "deviation_types": dev_types}


def stability_b(normal: dict, alt: dict) -> dict[str, Any]:
    n = normal["n"]
    matched = sum(1 for a, b in zip(normal["chosen"], alt["chosen"])
                  if a == b)
    agreement = matched / n if n else 0.0
    lo, hi = _cp95_binomial(matched, n)
    return {"n": n, "matched": matched, "agreement": agreement,
            "cp95_lo": lo, "cp95_hi": hi,
            "gate": AGREEMENT_GATE,
            "status": "PASS" if agreement >= AGREEMENT_GATE else "FAIL",
            "gate_type": "point-estimate-only; CP interval = disclosure"}


def stability_c(m8: dict, m16: dict) -> dict[str, Any]:
    n = m8["n"]
    matched = sum(1 for a, b in zip(m8["chosen"], m16["chosen"])
                  if a == b)
