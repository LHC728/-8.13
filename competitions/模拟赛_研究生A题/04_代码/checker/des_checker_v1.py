# -*- coding: utf-8 -*-
"""G2-04 independent event-log replay checker (E2) for the G2-03 deterministic DES.

Role
----
This module is the INDEPENDENT log-replay checker (E2) for task package
G2-03-SPEC-V1.0.2 (G2-04 task: CR-V3.1 C08/C09/C10/C11/C12/C17/C18/C19/C20/C21
replay side).  It takes ONLY the immutable ``event_log`` (append-only JSONL /
JSON array), the frozen ``des_config``, the scripted fixture record, the
shared ``parameters.csv`` and (optionally) the run ``metrics`` block, and
INDEPENDENTLY recomputes every quantity that the frozen event_log_contract
requires:

  * bay occupancy coverage ``[0, T)`` per bay (device residency + physical
    turnover; 0.5h_overlap zero-duration IN folding rule),
  * A/B/C/E resource occupancy (capacity-1 BUSY intervals; IDLE elsewhere),
  * task release / start / end per (device, process, effective_attempt_no),
  * release_time frozenness (K9: device3 B retest release constant 8.5 h = 51
    ticks across the shift change),
  * effective_attempt_no advancement (cancelled fragments never advance; 1<2),
  * test outcome PASS/ABNORMAL vs the scripted outcomes (a completed effective
    test without a scripted outcome is an explicit MISSING_SCRIPTED_OUTCOME
    failure),
  * cancel reason (DEVICE_EXIT / SHIFT_INTERRUPT),
  * shift boundaries (SHIFT_CHANGE events + half-open intervals; completions
    settle before the shift change),
  * turnover phases (OUT_START/OUT_COMPLETE/IN_START/IN_COMPLETE + bay; the
    last device is never transported out),
  * device terminal state (PASSED/EXITED + terminal_reason) and D
    materialization timing (E2: at the A/B/C all-PASS timestamp, before the E
    TASK_RELEASE, never at the E ACTIVITY_START, never regenerated by an E
    retest, early-exit devices keep not_created),
  * T (the last terminal-judgment time == SIMULATION_END time),
  * the YXB / age ledger seam (per-process elapsed_hours sums incl. cancelled
    fragments, divided by shift_count * shift_length),
  * the frozen same-timestamp closure order (settle -> observe -> classify ->
    exit -> cancel -> E2 D -> shift -> release -> dispatch -> liveness),
  * the frozen acceptance values (T/S/PL/PW and the K9 YXB block) and the
    optional run metrics block.

Isolation (CR-V3.1/C19)
-----------------------
This module imports ONLY the Python standard library.  It NEVER imports,
reads, or executes anything under ``04_代码/main_model/`` (the main DES
engine), never imports other checker modules, never imports test modules and
never launches the main engine as a child process.  Its only inputs are the
immutable event_log, the frozen config, the scripted fixture, the shared
parameters.csv and the optional metrics block.  The static/dynamic isolation
proof lives in ``04_代码/tests/test_des_checker_v1.py``.

Time representation
-------------------
Every canonical time is an exact ``fractions.Fraction`` (parsed from decimal
or fraction strings; floats are explicitly rejected).  1 tick = 10 min =
1/6 h (G2-03-SPEC-V1.0.2 §9b.integer_time_scaling); every canonical time must
satisfy tick*6 being an integer (NonIntegerTickError otherwise).  All activity
intervals are half-open ``[start, end)``.

0.5h_overlap folding rule (V1.0.2)
----------------------------------
For the isolated ``0.5h_overlap`` profile the log may record
TURNOVER_OUT_START at ``t0`` and TURNOVER_OUT_COMPLETE / TURNOVER_IN_START /
TURNOVER_IN_COMPLETE all at ``t0 + 0.5h`` (zero-duration IN log
representation).  The physical bay occupancy is strictly ``[t0, t0 + 0.5h)``;
the checker folds the zero-length IN representation and never double-counts
bay occupancy.

Exit codes (CLI): 0 PASS, 1 FAIL (checker found differences), 2 validation
error (bad input), 3 checker internal failure, 4 file I/O.
"""

