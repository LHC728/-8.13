class DesEventLogChecker:
    """Replays an immutable event_log and independently recomputes all frozen
    replay quantities, comparing them against internal invariants, the
    scripted fixture, the frozen config/parameters and (optionally) the run
    metrics / frozen acceptance block."""

    def __init__(self, event_log: Any, config: dict, scripted: dict,
                 parameters: Optional[str] = None,
                 metrics: Optional[dict] = None) -> None:
        self._issues: list[CheckIssue] = []
        self._special: list[dict] = []
        self._recomputed: dict[str, Any] = {}
        self._cfg = self._parse_config(config)
        self._scripted_outcomes: dict[tuple, str] = {}
        self._real_states: dict[int, dict[str, str]] = {}
        self._acceptance: Optional[dict] = None
        self._fixture_id = self._parse_scripted(scripted)
        self._parameters = load_parameters(parameters)
        self._metrics = metrics if isinstance(metrics, dict) else None
        self._log, self._structural_ok = self._parse_event_log(event_log)

        # replay views (built lazily by run())
        self._records_by_type: dict[str, list[dict]] = {}
        self._tasks: dict[tuple, dict[str, Any]] = {}
        self._devices: dict[int, dict[str, Any]] = {}
        self._shifts: list[dict] = []
        self._turnovers: list[dict] = []
        self._T: Optional[Fraction] = None

    # ------------------------------------------------------------------
    # input parsing
    # ------------------------------------------------------------------

    def _parse_config(self, raw: dict) -> dict:
        if not isinstance(raw, dict):
            raise CheckerValidationError("config must be a JSON object")
        if raw.get("schema_version") != "des_config_v1":
            raise CheckerValidationError("config.schema_version must be 'des_config_v1'")
        if raw.get("random_enabled") is not False:
            raise CheckerValidationError("G2-03 is deterministic: random_enabled must be false")
        scenario = raw.get("scenario")
        if scenario not in ("q2_single_shift", "q3_two_shift", "isolated_small_case"):
            raise CheckerValidationError("config.scenario invalid: %r" % (scenario,))
        batch_size = raw.get("batch_size")
        if not isinstance(batch_size, int) or batch_size < 1:
            raise CheckerValidationError("config.batch_size must be a positive integer")
        shift_length = parse_hours(raw.get("shift_length_h"), "config.shift_length_h")
        if shift_length <= 0:
            raise CheckerValidationError("config.shift_length_h must be positive")
        shifts_per_day = raw.get("shifts_per_day")
        if not isinstance(shifts_per_day, int) or shifts_per_day < 1:
            raise CheckerValidationError("config.shifts_per_day must be a positive integer")
        durations_raw = raw.get("durations")
        if not isinstance(durations_raw, dict):
            raise CheckerValidationError("config.durations must be an object")
        durations: dict[str, Fraction] = {}
        for proc in PROCESSES:
            if proc not in durations_raw:
                raise CheckerValidationError("config.durations missing process %s" % proc)
            durations[proc] = parse_hours(durations_raw[proc], "config.durations.%s" % proc)
            if durations[proc] <= 0:
                raise CheckerValidationError("config.durations.%s must be positive" % proc)
        transport_out = parse_hours(raw.get("transport_out_h"), "config.transport_out_h")
        transport_in = parse_hours(raw.get("transport_in_h"), "config.transport_in_h")
        if transport_out < 0 or transport_in < 0:
            raise CheckerValidationError("transport durations must be non-negative")
        profile = raw.get("turnover_profile")
        if profile not in ("1h_literal", "0.5h_overlap"):
            raise CheckerValidationError("config.turnover_profile invalid: %r" % (profile,))
        if raw.get("key_schema_version") != "key_schema_v1":
            raise CheckerValidationError("config.key_schema_version must be 'key_schema_v1'")
        initial = raw.get("deterministic_initial_state")
        if not isinstance(initial, dict):
            raise CheckerValidationError("config.deterministic_initial_state must be an object")
        if initial.get("all_calibrated") is not True or initial.get("queues_empty") is not True:
            raise CheckerValidationError(
                "deterministic_initial_state.all_calibrated/queues_empty must be true")
        preloaded = initial.get("preloaded_devices")
        if not isinstance(preloaded, list) or not preloaded:
            raise CheckerValidationError("deterministic_initial_state.preloaded_devices invalid")
        expected_preload = [1] if batch_size == 1 else [1, 2]
        if list(preloaded) != expected_preload:
            raise CheckerValidationError(
                "SEM-21 initial-state rule: batch_size==%d requires preloaded_devices == %r, got %r"
                % (batch_size, expected_preload, list(preloaded)))
        # durations must be integer ticks (contract: tick*6 integer)
        for proc in PROCESSES:
            hours_to_ticks(durations[proc], "config.durations.%s" % proc)
        hours_to_ticks(transport_out, "config.transport_out_h")
        hours_to_ticks(transport_in, "config.transport_in_h")
        return {
            "scenario_id": raw.get("scenario_id") or "",
            "scenario": scenario,
            "batch_size": batch_size,
            "shift_length_h": shift_length,
            "shifts_per_day": shifts_per_day,
            "durations": durations,
            "transport_out_h": transport_out,
            "transport_in_h": transport_in,
            "turnover_profile": profile,
            "preloaded_devices": tuple(preloaded),
            "random_enabled": False,
            "key_schema_version": "key_schema_v1",
        }

    def _parse_scripted(self, raw: dict) -> str:
        if not isinstance(raw, dict):
            raise CheckerValidationError("scripted fixture must be a JSON object")
        fixture_id = raw.get("fixture_id")
        if not isinstance(fixture_id, str) or not fixture_id:
            raise CheckerValidationError("scripted fixture needs a non-empty fixture_id")
        outcomes_raw = raw.get("scripted_outcomes")
        if not isinstance(outcomes_raw, list):
            raise CheckerValidationError("scripted_outcomes must be a list")
        self._scripted_outcomes = {}
        for item in outcomes_raw:
            if not isinstance(item, dict):
                raise CheckerValidationError("scripted_outcomes items must be objects")
            device_id = item.get("device_id")
            process = item.get("process")
            attempt = item.get("effective_attempt_no")
            outcome = item.get("outcome")
            if not isinstance(device_id, int) or process not in PROCESSES \
                    or attempt not in (1, 2) or outcome not in ("PASS", "ABNORMAL"):
                raise CheckerValidationError("bad scripted outcome item: %r" % (item,))
            key = (device_id, process, attempt)
            if key in self._scripted_outcomes:
                raise CheckerValidationError("duplicate scripted outcome %r" % (key,))
            self._scripted_outcomes[key] = outcome
        real_raw = raw.get("scripted_real_states")
        if not isinstance(real_raw, dict):
            raise CheckerValidationError("scripted_real_states must be an object")
        self._real_states = {}
        for dev_key, state in real_raw.items():
            try:
                device_id = int(dev_key)
            except (TypeError, ValueError):
                raise CheckerValidationError("bad device key in scripted_real_states: %r" % dev_key)
            if not isinstance(state, dict):
                raise CheckerValidationError("real state of device %d must be an object" % device_id)
            parsed: dict[str, str] = {}
            for proc in ("A", "B", "C"):
                if state.get(proc) not in ("normal", "problem"):
                    raise CheckerValidationError(
                        "real state %s of device %d must be normal|problem" % (proc, device_id))
                parsed[proc] = state[proc]
            if state.get("D") not in ("normal", "problem", "not_created"):
                raise CheckerValidationError("real state D of device %d invalid" % device_id)
            parsed["D"] = state["D"]
            self._real_states[device_id] = parsed
        self._acceptance = raw.get("acceptance") if isinstance(raw.get("acceptance"), dict) else None
        return fixture_id

    def _parse_event_log(self, event_log: Any) -> tuple[list[dict], bool]:
        """Validate the envelope structure, seq monotonicity and per-type
        required fields.  Returns (records, structural_ok)."""
        if isinstance(event_log, dict) and isinstance(event_log.get("records"), list):
            records = event_log["records"]
        elif isinstance(event_log, list):
            records = event_log
        else:
            self._issue("C17", "event_log", "list or {records: [...]}", type(event_log).__name__,
                        "event_log must be a JSON array or an envelope object")
            return [], False
        if not records:
            self._issue("C17", "event_log", "non-empty", "empty",
                        "event_log is empty (explicit FAIL, never a silent PASS)")
            return [], False
        ok = True
        parsed: list[dict] = []
        expected_seq = 1
        prev_time: Optional[Fraction] = None
        for idx, rec in enumerate(records):
            loc = "record[%d]" % idx
            if not isinstance(rec, dict):
                self._issue("C17", loc, "object", type(rec).__name__,
                            "log record must be an object")
                ok = False
                continue
            seq = rec.get("seq")
            if not isinstance(seq, int) or seq != expected_seq:
                self._issue("C17", loc, "seq == %d" % expected_seq, seq,
                            "seq must be a strictly increasing integer starting at 1")
                ok = False
            expected_seq += 1
            event_type = rec.get("event_type")
            if event_type not in EVENT_TYPES:
                self._issue("C17", loc, "one of %s" % sorted(EVENT_TYPES), event_type,
                            "unknown event_type")
                ok = False
            try:
                t = parse_hours(rec.get("event_time"), "%s.event_time" % loc)
                hours_to_ticks(t, "%s.event_time" % loc)
            except CheckerValidationError as exc:
                self._issue("C17", loc, "exact rational string", rec.get("event_time"),
                            "invalid canonical time: %s" % exc)
                ok = False
                t = None
            except NonIntegerTickError as exc:
                self._issue("C18", loc, "integer-multiple-of-1/6h", rec.get("event_time"),
                            "time not on the 10-min tick grid: %s" % exc)
                ok = False
                t = None
            if t is not None:
                if prev_time is not None and t < prev_time:
                    self._issue("C18", loc, ">= %s" % frac_to_str(prev_time), frac_to_str(t),
                                "event_time goes backwards (time must be monotonic)")
                    ok = False
                prev_time = t
            # float time fields anywhere in the record are forbidden
            for tf in TIME_FIELDS:
                if tf in rec and isinstance(rec[tf], float):
                    self._issue("C17", "%s.%s" % (loc, tf), "exact rational string",
                                rec[tf], "float is forbidden as a canonical time")
                    ok = False
            for field_name in REQUIRED_FIELDS.get(event_type, ()):
                if rec.get(field_name) is None:
                    self._issue("C17", "%s.%s" % (loc, event_type),
                                "present", None,
                                "missing required field %s for event_type %s" % (field_name, event_type))
                    ok = False
            parsed.append(rec)
        sim_ends = [r for r in parsed if r.get("event_type") == "SIMULATION_END"]
        if len(sim_ends) != 1:
            self._issue("C17", "event_log", "exactly one SIMULATION_END", len(sim_ends),
                        "SIMULATION_END must appear exactly once (incomplete log is an explicit FAIL)")
            ok = False
        else:
            last = parsed[-1]
            if last.get("event_type") != "SIMULATION_END":
                self._issue("C18", "event_log", "SIMULATION_END as the last record",
                            last.get("event_type"), "SIMULATION_END must be the final record")
                ok = False
        return parsed, ok

    # ------------------------------------------------------------------
    # helpers
    # ------------------------------------------------------------------

    def _issue(self, check_id: str, location: str, expected: Any, actual: Any,
               message: str) -> None:
        self._issues.append(CheckIssue(check_id, location, expected, actual, message))

    def _task_key(self, rec: dict) -> tuple:
        return (rec.get("device_id"), rec.get("process"), rec.get("effective_attempt_no"))

    def _shift_interval(self, index: int) -> Optional[tuple[Fraction, Fraction, int]]:
        """(start, end, squad) of shift `index` per the frozen calendar, or None."""
        scenario = self._cfg["scenario"]
        length = self._cfg["shift_length_h"]
        if scenario == "q3_two_shift":
            day = index // self._cfg["shifts_per_day"]
            slot = index % self._cfg["shifts_per_day"]
            start = Fraction(day) * Fraction(24) + Fraction(slot) * length
            squad = 1 if index % 2 == 0 else 2
            return (start, start + length, squad)
        if scenario == "q2_single_shift":
            start = Fraction(index) * Fraction(24)
            return (start, start + length, 1)
        if index == 0:
            return (Fraction(0), length, 1)
        return None

    def _shift_at(self, t: Fraction) -> Optional[tuple[Fraction, Fraction, int]]:
        index = 0
        while True:
            iv = self._shift_interval(index)
            if iv is None:
                return None
            start, end, squad = iv
            if start <= t < end:
                return iv
            if t < start:
                return None
            index += 1

