    def _build_views(self) -> None:
        self._records_by_type = {}
        for rec in self._log:
            self._records_by_type.setdefault(rec.get("event_type"), []).append(rec)
        # tasks
        tasks: dict[tuple, dict[str, Any]] = {}
        for rec in self._log:
            et = rec.get("event_type")
            if et not in ("TASK_RELEASE", "ACTIVITY_START", "ACTIVITY_COMPLETE",
                          "TASK_CANCEL", "OBSERVATION_MATERIALIZED"):
                continue
            key = self._task_key(rec)
            if None in key:
                continue
            view = tasks.setdefault(key, {
                "release_time": None, "release_seq": None, "release_event_time": None,
                "starts": [], "completes": [], "cancels": [], "observations": [],
            })
            if et == "TASK_RELEASE":
                view["release_time"] = parse_hours(rec.get("release_time"), "TASK_RELEASE.release_time")
                view["release_event_time"] = parse_hours(rec.get("event_time"), "TASK_RELEASE.event_time")
                view["release_seq"] = rec.get("seq")
            elif et == "ACTIVITY_START":
                view["starts"].append(rec)
            elif et == "ACTIVITY_COMPLETE":
                view["completes"].append(rec)
            elif et == "TASK_CANCEL":
                view["cancels"].append(rec)
            elif et == "OBSERVATION_MATERIALIZED":
                view["observations"].append(rec)
        self._tasks = tasks
        # devices
        devices: dict[int, dict[str, Any]] = {}
        for rec in self._log:
            et = rec.get("event_type")
            device_id = rec.get("device_id")
            if device_id is None or not isinstance(device_id, int):
                continue
            dev = devices.setdefault(device_id, {
                "terminal_state": None, "terminal_time": None, "terminal_reason": None,
                "d_created": None, "d_state": "not_created", "exit_seq": None,
                "bay_id": None, "entry_time": None,
            })
            if et == "DEVICE_TERMINAL":
                dev["terminal_state"] = rec.get("terminal_state")
                dev["terminal_time"] = parse_hours(rec.get("event_time"), "DEVICE_TERMINAL.event_time")
                dev["terminal_reason"] = rec.get("terminal_reason")
            elif et == "DEVICE_EXIT":
                dev["exit_seq"] = rec.get("seq")
            elif et == "D_CREATED":
                dev["d_created"] = parse_hours(rec.get("event_time"), "D_CREATED.event_time")
                dev["d_state"] = rec.get("d_state")
            elif et == "ACTIVITY_START":
                if dev["bay_id"] is None:
                    dev["bay_id"] = rec.get("bay_id")
        self._devices = devices
        # shifts (from SHIFT_CHANGE records, in seq order)
        self._shifts = []
        for rec in self._log:
            if rec.get("event_type") != "SHIFT_CHANGE":
                continue
            self._shifts.append({
                "seq": rec.get("seq"),
                "time": parse_hours(rec.get("event_time"), "SHIFT_CHANGE.event_time"),
                "shift_index": rec.get("shift_index"),
                "shift_start": parse_hours(rec.get("shift_start"), "SHIFT_CHANGE.shift_start"),
                "shift_end": parse_hours(rec.get("shift_end"), "SHIFT_CHANGE.shift_end"),
                "on_duty_squad": rec.get("on_duty_squad"),
            })
        # turnovers
        self._turnovers = []
        for rec in self._log:
            et = rec.get("event_type")
            if et in ("TURNOVER_OUT_START", "TURNOVER_OUT_COMPLETE",
                      "TURNOVER_IN_START", "TURNOVER_IN_COMPLETE"):
                self._turnovers.append({
                    "seq": rec.get("seq"),
                    "event_type": et,
                    "time": parse_hours(rec.get("event_time"), "%s.event_time" % et),
                    "bay_id": rec.get("bay_id"),
                    "device_id": rec.get("device_id"),
                })
        self._turnovers.sort(key=lambda x: (x["time"], x["seq"]))
        # T
        ends = [r for r in self._log if r.get("event_type") == "SIMULATION_END"]
        if ends:
            self._T = parse_hours(ends[-1]["event_time"], "SIMULATION_END.event_time")

