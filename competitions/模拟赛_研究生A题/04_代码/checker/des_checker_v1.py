    def run(self) -> CheckReport:
        self._build_views()
        self._check_parameters_cross()
        self._check_shift_calendar()
        self._check_task_lifecycle()
        self._check_release_time()
        self._check_attempts()
        self._check_devices()
        self._check_turnovers()
        self._check_bay_coverage()
        self._check_resource_occupancy()
        self._check_same_timestamp_order()
        self._check_ledger_yxb()
        self._check_acceptance_and_metrics()
        self._check_k9_special()
        devices_summary: dict[str, Any] = {}
        for device_id in sorted(self._devices):
            dev = self._devices[device_id]
            devices_summary[str(device_id)] = {
                "terminal_state": dev["terminal_state"],
                "terminal_h": fmt_opt(dev["terminal_time"]),
                "d_state": dev["d_state"],
                "bay_id": dev["bay_id"],
            }
        self._recomputed["devices"] = devices_summary
        tasks_summary: dict[str, Any] = {}
        for key in sorted(self._tasks, key=lambda k: (k[0], PROCESS_ORDER[k[1]], k[2])):
            view = self._tasks[key]
            status = "COMPLETED" if view["completes"] else ("CANCELLED" if view["cancels"] else "RELEASED_UNFINISHED")
            finish = None
            if view["completes"]:
                finish = parse_hours(view["completes"][0].get("event_time"), "finish")
            elif view["cancels"]:
                finish = parse_hours(view["cancels"][0].get("event_time"), "cancel")
            outcome = None
            if view["observations"]:
                outcome = view["observations"][0].get("outcome")
            tasks_summary["D%03d_%s_%d" % key] = {
                "status": status,
                "release_h": fmt_opt(view["release_time"]),
                "start_h": fmt_opt(parse_hours(view["starts"][0].get("event_time"), "start"))
                if view["starts"] else None,
                "finish_h": fmt_opt(finish),
                "outcome": outcome,
            }
        self._recomputed["tasks"] = tasks_summary
        verdict = "PASS" if not self._issues else "FAIL"
        return CheckReport(
            fixture_id=self._fixture_id,
            scenario_id=self._cfg["scenario_id"],
            verdict=verdict,
            issues=self._issues,
            special_assertions=self._special,
            recomputed=self._recomputed,
            metadata={
                "registry_version": REGISTRY_VERSION,
                "check_ids": list(CHECK_IDS),
                "turnover_profile": self._cfg["turnover_profile"],
                "scenario": self._cfg["scenario"],
                "batch_size": self._cfg["batch_size"],
                "event_log_records": len(self._log),
                "task_package_ref": "G2-03-SPEC-V1.0.2",
            },
        )


