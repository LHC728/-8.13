def _load_json_or_jsonl(path: str) -> Any:
    try:
        with open(path, "r", encoding="utf-8") as handle:
            text = handle.read()
    except OSError as exc:
        raise CheckerValidationError("cannot read %s: %s" % (path, exc)) from exc
    stripped = text.lstrip()
    if stripped.startswith("["):
        return json.loads(text)
    records = []
    for line_no, line in enumerate(text.splitlines(), start=1):
        line = line.strip()
        if not line:
            continue
        try:
            records.append(json.loads(line))
        except json.JSONDecodeError as exc:
            raise CheckerValidationError(
                "invalid JSONL at %s line %d: %s" % (path, line_no, exc)) from exc
    return records


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="G2-04 independent event-log replay checker (CR-V3.1 C17/C19).")
    parser.add_argument("--event-log", required=True, help="immutable event_log (JSON array or JSONL)")
    parser.add_argument("--config", required=True, help="frozen des_config JSON")
    parser.add_argument("--fixture", required=True, help="scripted fixture record JSON")
    parser.add_argument("--parameters", default=None, help="shared parameters.csv")
    parser.add_argument("--metrics", default=None, help="optional run metrics JSON")
    parser.add_argument("--report", default=None, help="optional output path for the report JSON")
    args = parser.parse_args(argv)
    try:
        event_log = _load_json_or_jsonl(args.event_log)
        with open(args.config, "r", encoding="utf-8") as handle:
            config = json.load(handle)
        with open(args.fixture, "r", encoding="utf-8") as handle:
            fixture = json.load(handle)
        metrics = None
        if args.metrics:
            with open(args.metrics, "r", encoding="utf-8") as handle:
                metrics = json.load(handle)
        report = check_event_log(event_log, config, fixture,
                                 parameters=args.parameters, metrics=metrics)
        output = json.dumps(report.to_dict(), ensure_ascii=False, indent=2, sort_keys=True)
        if args.report:
            with open(args.report, "w", encoding="utf-8") as handle:
                handle.write(output + "\n")
        else:
            print(output)
        return 0 if report.verdict == "PASS" else 1
    except NonIntegerTickError as exc:
        print("CHECKER_TICK_ERROR: %s" % exc, file=sys.stderr)
        return 1
    except CheckerValidationError as exc:
        print("CHECKER_VALIDATION_ERROR: %s" % exc, file=sys.stderr)
        return 2
    except CheckerNumericalError as exc:
        print("CHECKER_NUMERICAL_ERROR: %s" % exc, file=sys.stderr)
        return 3
    except OSError as exc:
        print("CHECKER_IO_ERROR: %s" % exc, file=sys.stderr)
        return 4
    except json.JSONDecodeError as exc:
        print("CHECKER_JSON_ERROR: %s" % exc, file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
