class CheckerError(Exception):
    """Base class for checker failures."""


class CheckerValidationError(CheckerError):
    """Invalid input (config / fixture / log envelope); CLI exit 2."""


class NonIntegerTickError(CheckerError):
    """A canonical time is not an integer multiple of 1/6 h (explicit FAIL)."""


class CheckerNumericalError(CheckerError):
    """Checker-internal numerical failure; CLI exit 3."""


def parse_hours(value: Any, ctx: str = "time") -> Fraction:
    """Parse a canonical time exactly.  Floats/bools are explicitly rejected."""
    if isinstance(value, bool):
        raise CheckerValidationError("%s: boolean is not a rational time: %r" % (ctx, value))
    if isinstance(value, float):
        raise CheckerValidationError(
            "%s: float is forbidden as canonical time: %r (use exact strings)" % (ctx, value))
    if isinstance(value, int):
        return Fraction(value)
    if isinstance(value, Fraction):
        return value
    if isinstance(value, str):
        text = value.strip()
        if not text:
            raise CheckerValidationError("%s: empty time string" % ctx)
        try:
            return Fraction(text)
        except (ValueError, ZeroDivisionError) as exc:
            raise CheckerValidationError(
                "%s: not a valid rational string: %r" % (ctx, value)) from exc
    raise CheckerValidationError(
        "%s: unsupported time type %s: %r" % (ctx, type(value).__name__, value))


def hours_to_ticks(value: Any, ctx: str = "time") -> int:
    """Hours -> integer ticks; fails explicitly when not a 1/6 h multiple."""
    f = parse_hours(value, ctx)
    ticks = f * TICKS_PER_HOUR
    if ticks.denominator != 1:
        raise NonIntegerTickError(
            "%s: %s h is not an integer multiple of 1/6 h (= %s ticks)" % (ctx, f, ticks))
    return int(ticks)


def frac_to_str(f: Fraction) -> str:
    """Fraction -> exact string (integer form when denominator == 1)."""
    f = Fraction(f)
    if f.denominator == 1:
        return str(f.numerator)
    return "%d/%d" % (f.numerator, f.denominator)


def fmt_opt(f: Optional[Fraction]) -> Optional[str]:
    return None if f is None else frac_to_str(f)


