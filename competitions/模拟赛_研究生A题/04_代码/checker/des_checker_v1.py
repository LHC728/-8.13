@dataclass
class CheckIssue:
    """One precise difference found by the checker."""

    check_id: str
    location: str
    expected: Any
    actual: Any
    message: str

    def to_dict(self) -> dict:
        return {
            "check_id": self.check_id,
            "location": self.location,
            "expected": _json_safe(self.expected),
            "actual": _json_safe(self.actual),
            "message": self.message,
        }

    def describe(self) -> str:
        return "[%s] %s: %s (expected=%r, actual=%r)" % (
            self.check_id, self.location, self.message,
            _json_safe(self.expected), _json_safe(self.actual))


def _json_safe(value: Any) -> Any:
    if isinstance(value, Fraction):
        return frac_to_str(value)
    if isinstance(value, tuple):
        return [_json_safe(v) for v in value]
    if isinstance(value, list):
        return [_json_safe(v) for v in value]
    if isinstance(value, dict):
        return {str(k): _json_safe(v) for k, v in value.items()}
    return value


@dataclass
class CheckReport:
    """Deterministic report of one checker run."""

    fixture_id: str
    scenario_id: str
    verdict: str  # PASS | FAIL
    issues: list[CheckIssue] = field(default_factory=list)
    special_assertions: list[dict] = field(default_factory=list)
    recomputed: dict[str, Any] = field(default_factory=dict)
    metadata: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict:
        return {
            "envelope_type": "des_check_report",
            "schema_version": "des_check_report_v1",
            "registry_version": REGISTRY_VERSION,
            "fixture_id": self.fixture_id,
            "scenario_id": self.scenario_id,
            "verdict": self.verdict,
            "issues": [i.to_dict() for i in self.issues],
            "special_assertions": _json_safe(self.special_assertions),
            "recomputed": _json_safe(self.recomputed),
            "metadata": _json_safe(self.metadata),
        }

    def summarize(self) -> str:
        return "%s %s T=%s ticks=%s %s (%d issues)" % (
            self.fixture_id,
            self.scenario_id,
            self.recomputed.get("T_h"),
            self.recomputed.get("T_ticks"),
            self.verdict,
            len(self.issues),
        )


