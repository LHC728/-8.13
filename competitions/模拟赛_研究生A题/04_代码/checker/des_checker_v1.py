def load_parameters(path: Optional[str]) -> dict[str, str]:
    """Read parameters.csv into {code_name: value} (shared read-only input)."""
    out: dict[str, str] = {}
    if path is None:
        return out
    try:
        with open(path, "r", encoding="utf-8-sig", newline="") as handle:
            reader = csv.DictReader(handle)
            for row in reader:
                pid = (row.get("parameter_id") or "").strip()
                if pid in _PARA_FIELDS:
                    out[_PARA_FIELDS[pid]] = (row.get("value") or "").strip()
    except OSError as exc:
        raise CheckerValidationError("cannot read parameters.csv: %s" % exc) from exc
    return out


